from datetime import datetime, timezone

from pydantic import Field, model_validator

from content_agent.models.base import (
    AppBaseModel,
    NonEmptyStr
)

from content_agent.models.enums import FailurePatternStatus


class FailurePattern(AppBaseModel):
    """
    Represents a recurring failure under a rubric criterion.

    Each failure pattern has an associated learned guideline.
    """

    id: int | None = None

    criterion_id: int = Field(gt=0)

    pattern_key: NonEmptyStr

    failure_pattern: NonEmptyStr

    learned_guideline: NonEmptyStr

    occurrence_count: int = Field(default=0, ge=0)

    distinct_run_count: int = Field(default=0, ge=0)

    status: FailurePatternStatus = (
        FailurePatternStatus.PROPOSED
    )

    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)
    )

    updated_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)
    )

    @model_validator(mode="after")
    def validate_occurrence_counts(self):

        if self.distinct_run_count > self.occurrence_count:
            raise ValueError(
                "Distinct run count cannot exceed "
                "total occurrence count."
            )

        return self


class EvaluationFailurePatternLink(AppBaseModel):
    """
    Links an individual evaluation failure
    to an identified failure pattern.
    """

    evaluation_id: int = Field(gt=0)

    failure_pattern_id: int = Field(gt=0)


class FailurePatternCandidate(AppBaseModel):
    """
    Candidate classification returned by the
    failure-pattern identification component.
    """

    criterion_id: int = Field(gt=0)

    pattern_key: NonEmptyStr

    failure_pattern: NonEmptyStr

    proposed_guideline: NonEmptyStr

    confidence: float = Field(ge=0.0, le=1.0)


class FailurePatternClassification(AppBaseModel):
    """
    LLM output for identifying a canonical failure pattern.

    criterion_id is deliberately not generated by the LLM.
    Python supplies it from the actual rubric criterion.
    """

    pattern_key: NonEmptyStr

    failure_pattern: NonEmptyStr

    proposed_guideline: NonEmptyStr

    confidence: float = Field(
        ge=0.0,
        le=1.0
    )


class GuidelineValidationResult(AppBaseModel):
    """
    Result of validating a proposed learned guideline.
    """

    approved: bool

    reason: NonEmptyStr

    revised_guideline: NonEmptyStr | None = None

    @model_validator(mode="after")
    def validate_approved_guideline(self):

        if self.approved and not self.revised_guideline:
            raise ValueError(
                "An approved guideline must contain "
                "a validated final guideline."
            )

        return self


class MemoryProcessingResult(AppBaseModel):
    """
    Summarizes the outcome of processing one evaluation failure.
    """

    processed: bool

    evaluation_id: int

    failure_pattern_id: int | None = None

    pattern_key: str | None = None

    occurrence_count: int = 0

    distinct_run_count: int = 0

    guideline_activated: bool = False

    message: NonEmptyStr